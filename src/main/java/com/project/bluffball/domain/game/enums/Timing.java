package com.project.bluffball.domain.game.enums;

/**
 * 투구 타이밍 구분 열거형.
 *
 * <p>타자 타격 세팅 화면의 5개 타이밍 슬롯(칸)을 표현한다.
 * 타자는 좌표 카드를 원하는 타이밍 칸 위에 올려 타이밍을 지정하며,
 * 투수의 구종 카드에 내재된 {@code timing} 값과의 차이로 타격 결과가 결정된다.</p>
 *
 * <pre>
 * ┌────────────────────────────┬─────┬──────────────────────────────────────────┐
 * │ 좌표·타이밍 판정              │ 주사위 │ 설명                                      │
 * ├────────────────────────────┼─────┼──────────────────────────────────────────┤
 * │ 좌표 정확 + 타이밍 차 = 0     │  2개  │ 완벽 일치 (볼존 접촉 시 합 −3)               │
 * │ 좌표 정확 + 타이밍 차 = 1     │  1개  │ 타이밍 빗맞음 (볼존 접촉 시 합 −3)            │
 * │ 좌표 상하좌우 ±1 + 타이밍 0   │  1개  │ 좌표 빗맞음 (볼존 접촉 시 합 −3)             │
 * │ 좌표 상하좌우 ±1 + 타이밍 1   │  1개  │ 합 −3 (+볼존이면 −6), 조정합 1 미만이면 파울 │
 * │ 그 외(좌표/타이밍 ≥ 2)       │  없음  │ 헛스윙 스트라이크                            │
 * └────────────────────────────┴─────┴──────────────────────────────────────────┘
 * </pre>
 *
 * <p>DB에는 ordinal(0~4) 정수로 저장된다.</p>
 */
public enum Timing {
    TOO_EARLY,  // 0 — 너무 이른 타이밍
    EARLY,      // 1 — 이른 타이밍
    NORMAL,     // 2 — 중간 타이밍
    LATE,       // 3 — 늦은 타이밍
    TOO_LATE    // 4 — 너무 늦은 타이밍
}
